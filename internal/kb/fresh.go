package kb

// Gate: a KB compile has actually been run for the source that changed.
//
// The graph checker asks whether the KB's edges RESOLVE. This asks whether
// anyone LOOKED at it. Those are different failures and only the second one
// produces a confidently-wrong article, which is worse than no article at all:
// an agent is instructed to read the KB first, so it acts on the stale text
// instead of reading the code.
//
// ## State is PER FILE, deliberately
//
// The manifest maps each KB-owned source path to a hash of its content at the
// last compile. Staleness is "this file's content differs from what was
// reviewed", which is the actual question.
//
// The design this replaced used a single `last_compiled_commit` stamp and
// diffed trees against it. That made every MERGE look like drift: bringing a
// trunk branch down into a feature branch changes the tree, so the branch owed
// a fresh compile for files someone had already reviewed on the other side.
// Three consecutive merge-downs produced three stamp-only "reviewed, already
// documented" commits — the check was measuring merges, not drift.
//
// Per-file hashes fix that by construction. Two branches compiling different
// files update separate entries and git merges them like any other file; two
// branches compiling the SAME file both keep their hash (see the format below),
// and the gate decides which review, if either, still describes the content.
//
// ## The manifest is NOT regenerated by a hook, on purpose
//
// The reverse index is derived from the KB, so being stale means being wrong,
// and a hook may rewrite it freely. This manifest is the opposite: it records
// a JUDGEMENT ("these articles were checked against this content"). Regenerate
// it automatically and the check passes always and means nothing.
//
// ## What it cannot do
//
// It cannot tell whether the compile was any GOOD — only that one happened for
// this content. A `--write` with no reading is indistinguishable from a careful
// pass. That is why the compile skill prints what it checked.

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"slices"
	"sort"
	"strings"
)

// The manifest is sorted text, three lines per file:
//
//	file internal/kb/fresh.go
//	sha256 9f2c...
//	end internal/kb/fresh.go
//
// The shape is the design, and it is shaped by how git merges rather than by
// what is easy to parse. Git conflicts on changes to touching lines, not only
// on the same line. The JSON this replaced, one `"path": "hash",` per line,
// conflicted for two branches that recorded neighbouring files, and sorted
// order puts a directory's files next to each other, so it was the norm for two
// people working on one subsystem. Adding a file after the last entry conflicted
// too, because it moved that entry's comma. Here every hash line sits between a
// `file` and an `end` line that only change when the path does. Blank-line
// separators do not work, because identical lines let the diff align a block
// insertion against the wrong blank.
//
// Two branches that recorded the SAME file still conflict, and with
// `merge=union` in .gitattributes they do not: both hash lines are kept, and
// a file is fresh when any of its recorded hashes matches its content. That is
// sound because the gate re-hashes every run. A union-kept hash for content
// that no longer exists can only make the file stale, never pass it. Whether
// GitHub's merge button honours the attribute was not tested (2026-11-06);
// without it, the conflict still resolves by keeping both sides' lines.
//
// The header and footer are constant, so they never conflict, and they keep
// an insert at either end from touching a changed hash line.
const (
	manifestHeader = "# kb-compile freshness manifest. Written by `kb compiled`.\n" +
		"# Per KB-owned file: the sha256 of the content last reviewed.\n"
	manifestFooter = "# end of manifest\n"
)

// legacyManifest is where builds before the line format kept the manifest. It
// is still read, so a repo keeps its reviews across the upgrade and a branch
// cut before it merges without losing them, and removed by the next write.
func legacyManifest(path string) string { return path + ".json" }

// ErrNoManifest reports an absent manifest.
//
// This is a FAILURE, never a skip. A missing manifest is indistinguishable
// from a deleted one, so skipping would make `rm .compiled-sources` a
// one-line bypass of the entire gate — the same shape as a test suite that
// passes because it found no tests. Its absence is not "nothing to check", it
// is "nothing is known". `kb compiled` is deliberately the only way to create
// one.
var ErrNoManifest = errors.New("manifest is missing")

// hasConflictMarkers reports whether data carries git conflict markers.
//
// Shared by the manifest and the two ratchet baselines, which are all one
// record per line for the same mergeability reason and so all conflict for the
// same reason. Every marker counts, not just the opening one: half-resolving
// by hand — delete `<<<<<<<` and the losing hunk, miss the tail — is the usual
// editor flow, and the leftover `=======` or `>>>>>>>` is exactly the state
// where the reader most needs to be told what NOT to do. Matching per line
// rather than anywhere in the file keeps a legitimate run of `=` in content
// from reading as a conflict.
func hasConflictMarkers(data []byte) bool {
	for _, l := range bytes.Split(data, []byte("\n")) {
		t := bytes.TrimRight(l, "\r")
		if bytes.HasPrefix(t, []byte("<<<<<<<")) ||
			bytes.HasPrefix(t, []byte(">>>>>>>")) ||
			bytes.HasPrefix(t, []byte("|||||||")) ||
			bytes.Equal(t, []byte("=======")) {
			return true
		}
	}
	return false
}

// Stale is one file whose content has moved since it was last reviewed.
type Stale struct {
	Path     string
	Articles []string
	Reason   string // "changed", "new", or "unreviewed"
}

// Freshness compares the manifest against the current content of every
// KB-owned source file. ownership comes from the graph pass, so the two
// checkers cannot disagree about what the KB owns.
func Freshness(manifestPath string, ownership map[string][]string) ([]Stale, map[string]string, error) {
	recorded, err := ReadManifest(manifestPath)
	missing := errors.Is(err, ErrNoManifest)
	if err != nil && !missing {
		return nil, nil, err
	}

	current := map[string]string{}
	var stale []Stale
	paths := make([]string, 0, len(ownership))
	for p := range ownership {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	for _, p := range paths {
		// Only files with an owning ARTICLE. A file the index lists for its
		// test links alone has nothing to re-read, so failing on it would
		// hand the agent a filename and no scope — which is the "go read the
		// KB" outcome this check exists to replace.
		if len(ownership[p]) == 0 {
			continue
		}
		data, err := os.ReadFile(p)
		if err != nil {
			// A file the KB owns that is no longer readable is the graph
			// checker's problem, not this one's. Skip rather than double-report.
			continue
		}
		sum := sha256.Sum256(data)
		h := hex.EncodeToString(sum[:])
		current[p] = h

		prev, seen := recorded[p]
		switch {
		case !seen:
			stale = append(stale, Stale{p, ownership[p], "new"})
		case !slices.Contains(prev, h):
			stale = append(stale, Stale{p, ownership[p], "changed"})
		}
	}
	if missing {
		return stale, current, ErrNoManifest
	}
	return stale, current, nil
}

// ReadManifest returns every hash recorded for each path, from the manifest and
// from a legacy JSON manifest beside it. A path can carry more than one hash
// after a union merge, and it is fresh when any of them matches.
func ReadManifest(path string) (map[string][]string, error) {
	recorded := map[string][]string{}
	add := func(p, h string) {
		if !slices.Contains(recorded[p], h) {
			recorded[p] = append(recorded[p], h)
		}
	}
	found := false

	data, err := os.ReadFile(path)
	switch {
	case err == nil:
		found = true
		if err := parseManifest(path, data, add); err != nil {
			return nil, err
		}
	case !os.IsNotExist(err):
		return nil, err
	}

	// Both can exist after a branch cut before the upgrade merges into one cut
	// after it. Reading both keeps the other side's reviews instead of making
	// them look unreviewed.
	legacy := legacyManifest(path)
	data, err = os.ReadFile(legacy)
	switch {
	case err == nil:
		found = true
		if hasConflictMarkers(data) {
			return nil, conflictError(legacy)
		}
		old := map[string]string{}
		if err := json.Unmarshal(data, &old); err != nil {
			return nil, fmt.Errorf("%s is not valid JSON: %w", legacy, err)
		}
		for p, h := range old {
			add(p, h)
		}
	case !os.IsNotExist(err):
		return nil, err
	}

	if !found {
		return recorded, ErrNoManifest
	}
	return recorded, nil
}

func parseManifest(path string, data []byte, add func(p, h string)) error {
	if hasConflictMarkers(data) {
		return conflictError(path)
	}
	cur := ""
	for i, line := range strings.Split(string(data), "\n") {
		line = strings.TrimRight(line, "\r")
		bad := func(why string) error {
			return fmt.Errorf("%s:%d: %s: %q. Fix the line by hand, or rewrite "+
				"the file from the version in git; never by `kb compiled`, "+
				"which records every file as reviewed.", path, i+1, why, line)
		}
		switch {
		case line == "" || strings.HasPrefix(line, "#"):
		case strings.HasPrefix(line, "file "):
			if cur != "" {
				return bad("`file` before the `end` of " + cur)
			}
			cur = strings.TrimPrefix(line, "file ")
		case strings.HasPrefix(line, "sha256 "):
			if cur == "" {
				return bad("hash outside any entry")
			}
			add(cur, strings.TrimPrefix(line, "sha256 "))
		case strings.HasPrefix(line, "end "):
			if strings.TrimPrefix(line, "end ") != cur {
				return bad("`end` does not match `file " + cur + "`")
			}
			cur = ""
		default:
			return bad("not a manifest line")
		}
	}
	if cur != "" {
		return fmt.Errorf("%s: the entry for %s has no `end` line, so the file "+
			"is truncated or half-edited", path, cur)
	}
	return nil
}

// conflictError explains the conflict that remains when git ran without the
// union attribute.
//
// It has to rule out the obvious fix. `kb compiled` would resolve it by
// blanket-approving every file on both sides unreviewed, which is precisely the
// review that was about to be arbitrated.
func conflictError(path string) error {
	return fmt.Errorf(
		"%s has unresolved merge conflict markers.\n\n"+
			"Two branches recorded a review of the same file, or of files "+
			"next to each other. Resolve it by deleting the marker lines and "+
			"keeping both sides' lines. A file is fresh when any hash recorded "+
			"for it matches its content, so keeping both cannot pass a file "+
			"nobody reviewed.\n\n"+
			"Do NOT resolve it with `kb compiled`. That would "+
			"re-record every file on both sides as reviewed, "+
			"including the ones nobody looked at, which is the one "+
			"use that defeats this gate.", path)
}

// WriteManifest records a compile. Only ever called by an explicit `kb
// compiled`, never by a hook.
func WriteManifest(path string, sources map[string]string) error {
	all := make(map[string][]string, len(sources))
	for p, h := range sources {
		all[p] = []string{h}
	}
	return writeManifest(path, all)
}

func writeManifest(path string, recorded map[string][]string) error {
	paths := make([]string, 0, len(recorded))
	for p := range recorded {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	var b strings.Builder
	b.WriteString(manifestHeader)
	for _, p := range paths {
		hashes := slices.Clone(recorded[p])
		sort.Strings(hashes)
		fmt.Fprintf(&b, "file %s\n", p)
		for _, h := range hashes {
			fmt.Fprintf(&b, "sha256 %s\n", h)
		}
		fmt.Fprintf(&b, "end %s\n", p)
	}
	b.WriteString(manifestFooter)
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return err
	}
	// Everything the legacy file held was read into recorded first.
	if err := os.Remove(legacyManifest(path)); err != nil && !os.IsNotExist(err) {
		return err
	}
	return nil
}

// MergeManifest records a review of SOME articles, leaving the rest as they
// were.
//
// `kb compiled` used to record every KB-owned file at once, because per-file
// recording lets you assert coverage you do not have, one file at a time,
// until the gate is green and means nothing. That reasoning is sound and it
// produced a failure nobody anticipated: an agent who had genuinely reviewed
// three of the five articles the gate named, and genuinely not reviewed the
// other two, had exactly one truthful option — record nothing and leave the
// gate red. Which is the output a careless agent produces too. The gate could
// not tell the honest one from the negligent one, so the honesty cost the
// honest agent everything and bought no information.
//
// The rule the coarse version got wrong: the granularity of the RECORD has to
// match the granularity of the CHECK. `kb fresh` names articles individually,
// so the record has to be able to name a subset. The anti-gaming argument does
// not call for coarseness — it calls for each claim to be specific and
// attributable, which is the opposite.
func MergeManifest(path string, current map[string]string, files []string) (int, error) {
	// Read what is already recorded rather than taking it from the caller:
	// a partial record must preserve every judgement it is not replacing, and
	// the manifest on disk is the only authority on those.
	merged, err := ReadManifest(path)
	if err != nil && !errors.Is(err, ErrNoManifest) {
		return 0, err
	}
	n := 0
	for _, f := range files {
		h, ok := current[f]
		if !ok {
			// No longer owned or no longer present: recording a hash for it
			// would assert a review of something that is not there.
			continue
		}
		if !slices.Equal(merged[f], []string{h}) {
			n++
		}
		// The review replaces whatever a union merge left: it was made against
		// this content, so the other hashes describe nothing that is here.
		merged[f] = []string{h}
	}
	return n, writeManifest(path, merged)
}

// GroupByArticle renders stale files grouped by the article that owns them, so
// the re-read is SCOPED rather than "go read the KB". This grouping is the
// output the compile skill consumes as its work list; it is more precise than
// a commit range, because a file touched and reverted since the last compile
// does not appear at all.
func GroupByArticle(stale []Stale) string {
	byArticle := map[string][]string{}
	var unowned []string
	for _, s := range stale {
		if len(s.Articles) == 0 {
			unowned = append(unowned, s.Path)
			continue
		}
		for _, a := range s.Articles {
			byArticle[a] = append(byArticle[a], s.Path+"  ("+s.Reason+")")
		}
	}
	ids := make([]string, 0, len(byArticle))
	for a := range byArticle {
		ids = append(ids, a)
	}
	sort.Strings(ids)

	var b strings.Builder
	for _, a := range ids {
		files := byArticle[a]
		sort.Strings(files)
		fmt.Fprintf(&b, "  %s.md\n", a)
		for _, f := range files {
			fmt.Fprintf(&b, "    %s\n", f)
		}
	}
	if len(unowned) > 0 {
		sort.Strings(unowned)
		b.WriteString("  (no owning article — the graph checker's orphan ratchet covers these)\n")
		for _, f := range unowned {
			fmt.Fprintf(&b, "    %s\n", f)
		}
	}
	return b.String()
}
